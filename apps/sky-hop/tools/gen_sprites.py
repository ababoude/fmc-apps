#!/usr/bin/env python3
"""Turns the Flappy-style PNG sprites into src/sprites.rs: lists of opaque rects (x, y, w, h, rgb565), because the
watch's only pixel primitive is a filled rect. Usage: gen_sprites.py <sprites dir> > src/sprites.rs"""
import struct, sys, zlib

def png(path):
    d = open(path, 'rb').read()
    pos, chunks = 8, {}
    idat = b''
    while pos < len(d):
        n, t = struct.unpack('>I4s', d[pos:pos + 8])
        body = d[pos + 8:pos + 8 + n]
        if t == b'IDAT': idat += body
        else: chunks[t] = body
        pos += 12 + n
    w, h, depth, ctype = struct.unpack('>IIBB', chunks[b'IHDR'][:10])
    assert ctype in (3, 6) and depth in (1, 2, 4, 8), (path, ctype, depth)
    pal = chunks.get(b'PLTE')
    trns = chunks.get(b'tRNS', b'')
    raw = zlib.decompress(idat)
    bpp = 4 if ctype == 6 else 1
    stride = (w * depth + 7) // 8 * (4 if ctype == 6 else 1)
    rows, prev = [], bytearray(stride)
    for y in range(h):
        f = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pr = a if pa <= pb and pa <= pc else b if pb <= pc else c
                line[i] = (line[i] + pr) & 255
        rows.append(line)
        prev = line
    img = []
    for line in rows:
        out = []
        for x in range(w):
            if ctype == 6:
                r, g, b, alpha = line[x * 4:x * 4 + 4]
                out.append(None if alpha < 128 else ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
                continue
            bit = x * depth
            idx = (line[bit // 8] >> (8 - depth - bit % 8)) & ((1 << depth) - 1)
            alpha = trns[idx] if idx < len(trns) else 255
            r, g, b = pal[idx * 3:idx * 3 + 3]
            out.append(None if alpha < 128 else ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
        img.append(out)
    return w, h, img

def rects(img, x0=0, y0=0, x1=None, y1=None):
    """Greedy merge of equal-coloured pixels into rects, opaque pixels only."""
    x1 = x1 if x1 is not None else len(img[0])
    y1 = y1 if y1 is not None else len(img)
    seen = set()
    out = []
    for y in range(y0, y1):
        for x in range(x0, x1):
            c = img[y][x]
            if c is None or (x, y) in seen: continue
            w = 1
            while x + w < x1 and img[y][x + w] == c and (x + w, y) not in seen: w += 1
            h = 1
            while y + h < y1 and all(img[y + h][x + i] == c and (x + i, y + h) not in seen for i in range(w)): h += 1
            for j in range(h):
                for i in range(w): seen.add((x + i, y + j))
            out.append((x - x0, y - y0, w, h, c))
    return out

def emit(name, w, h, rs):
    print(f"pub const {name.upper()}: Sprite = Sprite {{ w: {w}, h: {h}, rects: &[")
    for r in rs: print("    (%d, %d, %d, %d, 0x%04X)," % r)
    print("] };\n")

d = sys.argv[1]
print("// Generated by tools/gen_sprites.py from the sprite PNGs: do not edit.\n")
print("/// Opaque rects of a sprite: (x, y, w, h, rgb565).")
print("pub struct Sprite {\n    pub w: i32,\n    pub h: i32,\n    pub rects: &'static [(i16, i16, i16, i16, u16)],\n}\n")
for i in range(10):
    w, h, img = png(f"{d}/{i}.png"); emit(f"digit{i}", w, h, rects(img))
for n, name in enumerate(['up', 'mid', 'down']):
    w, h, img = png(f"{d}/yellowbird-{name}flap.png"); emit(f"bird_{name}", w, h, rects(img))
w, h, img = png(f"{d}/gameover.png"); emit("gameover", w, h, rects(img))
# The title screen without its "FlappyBird" logo (the top rows): "Get Ready!" and the tap hint.
w, h, img = png(f"{d}/message.png"); emit("message", w, h - 80, rects(img, 0, 80, w, h))

# The pipe: a cap on top of a shaft. The cap is rects; the shaft is one representative row that the view stretches
# to any length.
w, h, img = png(f"{d}/pipe-green.png")
cap = 26  # rows 0..25: the wider cap and its dark lower edge; below it the shaft only varies by faint noise
print(f"pub const PIPE_W: i32 = {w};\npub const PIPE_CAP_H: i32 = {cap};\n")
# The cap's rounded corners and the shaft's margins are black, not transparent: the pipe moves in steps and must
# cover what the last step left there.
img = [[0 if c is None else c for c in row] for row in img]
emit("pipe_cap", w, cap, rects(img, 0, 0, w, cap))
body = rects([img[160]], 0, 0, w, 1)
emit("pipe_body", w, 1, body)

# The scenery: plain sky above, and the strip with the clouds, the town and the grass along the bottom (drawn twice
# side by side to cover the screen's width).
w, h, img = png(f"{d}/background-day.png")
sky = img[0][0]
top = next(y for y in range(h) if img[y][0] != sky or len(set(img[y])) > 1)
print(f"pub const SKY: u16 = 0x{sky:04X};\n")
emit("band", w, h - top, rects(img, 0, top, w, h))
